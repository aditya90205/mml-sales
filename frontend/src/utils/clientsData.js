const EVENT = "mml-sales-clients";

function emit() {
  if (typeof window === "undefined") return;
  window.dispatchEvent(new Event(EVENT));
}

function digitsOnly(value = "") {
  return String(value).replace(/\D/g, "");
}

const CLIENT_SERIES_PREFIX = {
  unpaid: "1000",
  committed: "3000",
  paid: "5000",
};

const CLIENT_SERIAL_START = 6803;

function nextClientSerial() {
  let max = CLIENT_SERIAL_START - 1;
  for (const client of CLIENTS) {
    const serial = Number(String(client.clientId || "").slice(-4));
    if (Number.isFinite(serial) && serial >= CLIENT_SERIAL_START && serial > max) max = serial;
  }
  return max + 1;
}

function buildClientId(series = "unpaid") {
  const prefix = CLIENT_SERIES_PREFIX[series] || CLIENT_SERIES_PREFIX.unpaid;
  return `${prefix}${String(nextClientSerial()).padStart(4, "0")}`;
}

function todayLabel() {
  const d = new Date();
  const dd = String(d.getDate()).padStart(2, "0");
  const mm = String(d.getMonth() + 1).padStart(2, "0");
  const yy = String(d.getFullYear()).slice(-2);
  return `${dd}/${mm}/${yy}`;
}

export function readClients() {
  return CLIENTS.map((c) => ({ ...c }));
}

export function subscribeClients(onChange) {
  if (typeof window === "undefined") return () => {};
  const handler = () => onChange();
  window.addEventListener(EVENT, handler);
  return () => window.removeEventListener(EVENT, handler);
}

export function findClientById(id) {
  if (id == null || id === "") return null;
  const hit = CLIENTS.find((c) => String(c.id) === String(id));
  return hit ? { ...hit } : null;
}

export function findClientByName(name) {
  const q = String(name || "").trim().toLowerCase();
  if (!q) return null;
  const hit = CLIENTS.find((c) => String(c.name || "").toLowerCase() === q);
  return hit ? { ...hit } : null;
}

export function updateClient(id, patch = {}) {
  const idx = CLIENTS.findIndex((c) => String(c.id) === String(id));
  if (idx < 0) return null;
  CLIENTS[idx] = { ...CLIENTS[idx], ...patch, id: CLIENTS[idx].id };
  emit();
  return { ...CLIENTS[idx] };
}

